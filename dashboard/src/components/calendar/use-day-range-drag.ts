import { useCallback, useEffect, useRef, useState } from "react";

// Drag across day cells to pick a date range.
//
// The gesture only becomes a range once it reaches a *second* day. That is what
// keeps it from stealing the plain click that opens the day-plan dialog: press
// and release inside one cell stays a click, crossing into another cell becomes
// a range. It also means a single-day entry is made from the toolbar rather
// than by drag, which is the trade for not breaking the existing interaction.
export function useDayRangeDrag(onComplete: (from: string, to: string) => void) {
	// Both are 'YYYY-MM-DD' keys, which compare correctly as strings.
	const [anchor, setAnchor] = useState<string | null>(null);
	const [hover, setHover] = useState<string | null>(null);
	const swallowClick = useRef(false);
	const complete = useRef(onComplete);
	complete.current = onComplete;

	// Bounds of the current selection, low to high, so dragging backwards across
	// the calendar works the same as forwards. Null until a second day is
	// reached, which is what distinguishes a drag from a click.
	let bounds: readonly [string, string] | null = null;
	if (anchor !== null && hover !== null && hover !== anchor) {
		bounds = anchor < hover ? [anchor, hover] : [hover, anchor];
	}
	const dragging = bounds !== null;

	// Release anywhere ends the gesture -- including outside the calendar, which
	// is why this is on the window rather than the cells.
	useEffect(() => {
		if (anchor === null) return;
		const finish = () => {
			if (bounds) {
				// The click generated by this release would otherwise also open the
				// day-plan dialog on top of the journal one.
				swallowClick.current = true;
				complete.current(bounds[0], bounds[1]);
			}
			setAnchor(null);
			setHover(null);
		};
		window.addEventListener("pointerup", finish);
		window.addEventListener("pointercancel", finish);
		return () => {
			window.removeEventListener("pointerup", finish);
			window.removeEventListener("pointercancel", finish);
		};
	}, [anchor, bounds]);

	const dayProps = useCallback(
		(key: string) => ({
			onPointerDown: (event: React.PointerEvent) => {
				// Left button only, and only from the cell's own empty-space layer so
				// plan chips keep their own drag and journal chips keep their click.
				if (event.button !== 0) return;
				if (!(event.target as HTMLElement).closest("[data-cell-hit]")) return;
				setAnchor(key);
				setHover(key);
			},
			onPointerEnter: () => {
				setAnchor((current) => {
					if (current !== null) setHover(key);
					return current;
				});
			},
		}),
		[],
	);

	const inRange = useCallback(
		(key: string) => Boolean(bounds && key >= bounds[0] && key <= bounds[1]),
		[bounds],
	);

	const shouldIgnoreClick = useCallback(() => {
		if (!swallowClick.current) return false;
		swallowClick.current = false;
		return true;
	}, []);

	return { dayProps, inRange, shouldIgnoreClick, dragging };
}
